#!/usr/bin/env python3
"""run_flatk3_gen.py -- generate the flat-vector k=3 arm with the CANONICAL driver, metered.

Generation itself is `generate_colpali.main()`, unmodified and called directly: the flat k=3 arm
must be generated by exactly the code that generated every arm it will be compared against (the
C-49 rule). This wrapper adds two things the canonical driver does not have:

  1. TOKEN METERING. `VLMClient` returns only the text, so no run in this project has ever recorded
     what it actually spent -- every cost in the register is a calibrated estimate. Here the OpenAI
     SDK's `chat.completions.create` is wrapped to accumulate `resp.usage`, which is exact and
     includes image tokens. The wrapper touches observability only; the request is unchanged.
  2. A SPEND CEILING. Token cost is evaluated after every call; crossing the ceiling raises, which
     the driver's own fail-fast turns into a checkpointed stop rather than a silent overrun.

Prices are STAMPED, not looked up at runtime: the dollar figure is an estimate at the stamped rate
and the authoritative number is the OpenAI dashboard. Tokens are the measurement.

  python run_flatk3_gen.py <bench> [--limit N] [--ceiling-usd X]
"""
import argparse, atexit, json, os, sys, threading, time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

# Stamped 2026-09-28. gpt-4.1-mini, USD per 1M tokens. An estimate, clearly labelled as one.
PRICE = {"gpt-4.1-mini": {"in": 0.40, "out": 1.60}}

METER = {"calls": 0, "prompt_tokens": 0, "completion_tokens": 0, "started": time.time()}
_lock = threading.Lock()
OUT = HERE / "cost"


def usd(m=None):
    m = m or METER
    p = PRICE["gpt-4.1-mini"]
    return m["prompt_tokens"] / 1e6 * p["in"] + m["completion_tokens"] / 1e6 * p["out"]


def install_meter(ceiling):
    import openai
    orig = openai.resources.chat.completions.Completions.create

    def wrapped(self, *args, **kw):
        resp = orig(self, *args, **kw)
        u = getattr(resp, "usage", None)
        if u is not None:
            with _lock:
                METER["calls"] += 1
                METER["prompt_tokens"] += int(getattr(u, "prompt_tokens", 0) or 0)
                METER["completion_tokens"] += int(getattr(u, "completion_tokens", 0) or 0)
                spend = usd()
            if ceiling is not None and spend > ceiling:
                raise SystemExit(f"FATAL: spend ceiling ${ceiling:.2f} crossed "
                                 f"(estimated ${spend:.2f} over {METER['calls']} calls) -- stopping")
        return resp

    openai.resources.chat.completions.Completions.create = wrapped


def report(bench, limit):
    m = dict(METER)
    m["wall_s"] = round(time.time() - m.pop("started"), 1)
    if not m["calls"]:
        print("meter: no calls recorded"); return
    m["usd_estimated"] = round(usd(m), 4)
    m["usd_per_call"] = round(usd(m) / m["calls"], 6)
    m["prompt_tokens_per_call"] = round(m["prompt_tokens"] / m["calls"], 1)
    m["price_stamped"] = PRICE["gpt-4.1-mini"]
    m["bench"], m["limit"] = bench, limit
    OUT.mkdir(parents=True, exist_ok=True)
    f = OUT / f"flatk3_gen_meter_{bench}{'_calib' if limit else ''}.json"
    f.write_text(json.dumps(m, indent=1))
    print(f"\nMETER {bench}: {m['calls']} calls, {m['prompt_tokens']:,} in + "
          f"{m['completion_tokens']:,} out tokens, ${m['usd_estimated']:.4f} estimated "
          f"(${m['usd_per_call']:.5f}/call), {m['wall_s']}s -> {f.name}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("bench")
    ap.add_argument("--limit", type=int, default=None)
    ap.add_argument("--ceiling-usd", type=float, default=17.0)
    ap.add_argument("--arm", default="flatk3",
                    help="MP-DocVQA only: which generate_p3 arm to run (use an existing arm to "
                         "probe per-call image cost without producing a result)")
    a = ap.parse_args()
    if not os.environ.get("OPENAI_API_KEY"):
        sys.exit("FATAL: OPENAI_API_KEY absent -- refusing to run")
    install_meter(a.ceiling_usd)
    atexit.register(report, a.bench, a.limit)

    if a.bench == "mpdocvqa":
        # MP-DocVQA's canonical generator is generate_p3.py: 0-based pages and the corpus's own
        # JPGs, which generate_colpali's 1-based renderer would silently get wrong.
        sys.path.insert(0, str(HERE.parent / "gramm-rag-graphbracket"))
        import generate_p3 as GP
        print(f"canonical driver: {GP.__file__}", flush=True)  # rule 22
        sys.argv = ["generate_p3.py", "--arm", a.arm] + (["--limit", str(a.limit)] if a.limit else [])
        GP.main()
    else:
        import generate_colpali as GC
        print(f"canonical driver: {GC.__file__}", flush=True)  # rule 22
        sys.argv = ["generate_colpali.py", a.bench, "--arm", a.arm] + (
            ["--limit", str(a.limit)] if a.limit else [])
        GC.main()


if __name__ == "__main__":
    main()
